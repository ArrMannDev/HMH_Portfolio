import { NextResponse, type NextRequest } from "next/server";
import { AUTH_NO_STORE_HEADERS, authJson, authRedirect, getAuthOrigin, isSameOriginRequest } from "../../../../lib/auth/http";
import { createClient } from "../../../../lib/supabase/server";

export async function POST(request: NextRequest) {
  try {
    const origin = getAuthOrigin(request);
    if (!isSameOriginRequest(request, origin)) {
      return authJson({ error: "This request is not allowed." }, 403);
    }

    const supabase = await createClient({ writable: true });
    const { data, error } = await supabase.auth.signInWithOAuth({
      provider: "google",
      options: {
        redirectTo: `${origin}/api/auth/callback`,
        skipBrowserRedirect: true,
      },
    });

    if (error || !data.url) {
      return authRedirect(origin, "/dashboard/login?error=signin");
    }

    // The provider URL is generated by Supabase, not accepted from the request.
    return NextResponse.redirect(data.url, { status: 303, headers: AUTH_NO_STORE_HEADERS });
  } catch {
    return authJson({ error: "Sign-in is unavailable. Check the application configuration and try again." }, 503);
  }
}
